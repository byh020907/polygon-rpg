function rectangle(x, y, width, height) {
  return [
    { x, y },
    { x: x + width, y },
    { x: x + width, y: y + height },
    { x, y: y + height },
  ];
}

function polygon(cx, cy, radiusX, radiusY, sides, angleOffset = 0) {
  return Array.from({ length: sides }, (_, index) => {
    const angle = angleOffset + (index / sides) * Math.PI * 2;
    return { x: cx + Math.cos(angle) * radiusX, y: cy + Math.sin(angle) * radiusY };
  });
}

function scaleAround(points, originX, originY, scaleX, scaleY = scaleX) {
  return points.map((point) => ({
    x: originX + (point.x - originX) * scaleX,
    y: originY + (point.y - originY) * scaleY,
  }));
}

function item(id, points, fill, options = {}) {
  return {
    id,
    points,
    fill,
    stroke: options.stroke ?? '#17191a',
    lineWidth: options.lineWidth ?? 2,
    opacity: options.opacity ?? 1,
    order: options.order ?? 0,
    renderOrder: options.renderOrder ?? 30,
    enabled: options.enabled ?? true,
    presentationOnly: options.presentationOnly ?? true,
    parallax: options.parallax ?? 1,
    materialId: options.materialId ?? 'stone',
    surfaceNormal: options.surfaceNormal ?? { x: 0, y: -1 },
    lightOccluder: options.lightOccluder ?? false,
    emissive: options.emissive ?? false,
    ...(options.label ? { label: options.label } : {}),
    ...(options.role ? { role: options.role } : {}),
  };
}

function createVentilatorLandmarkItems(id, centerX, centerY) {
  const shared = {
    parallax: 0.34,
    materialId: 'metal',
    renderOrder: 30,
  };
  const blades = Array.from({ length: 8 }, (_, index) => {
    const angle = (index / 8) * Math.PI * 2;
    const nextAngle = angle + Math.PI / 7;
    const inner = 12;
    const outer = 34;
    return item(
      `${id}-blade-${index}`,
      [
        { x: centerX + Math.cos(angle) * inner, y: centerY + Math.sin(angle) * inner },
        {
          x: centerX + Math.cos(angle - 0.24) * outer,
          y: centerY + Math.sin(angle - 0.24) * outer,
        },
        {
          x: centerX + Math.cos(nextAngle) * outer * 0.9,
          y: centerY + Math.sin(nextAngle) * outer * 0.9,
        },
        {
          x: centerX + Math.cos(nextAngle) * inner,
          y: centerY + Math.sin(nextAngle) * inner,
        },
      ],
      index % 2 === 0 ? '#5a5e5a' : '#484c49',
      {
        ...shared,
        stroke: '#242724',
        lineWidth: 2,
        order: -61 + index * 0.01,
        surfaceNormal: { x: Math.cos(angle), y: Math.sin(angle) },
        role: 'ventilator-blade',
      },
    );
  });
  return [
    item(`${id}-housing`, polygon(centerX, centerY, 44, 42, 12, Math.PI / 12), '#303432', {
      ...shared,
      stroke: '#171918',
      lineWidth: 5,
      order: -64,
      lightOccluder: true,
      label: '붕괴 광산 대형 환기팬',
      role: 'industrial-landmark',
    }),
    item(`${id}-cavity`, polygon(centerX, centerY, 37, 35, 12, Math.PI / 12), '#161817', {
      ...shared,
      stroke: '#292c2a',
      lineWidth: 3,
      order: -63,
      role: 'ventilator-cavity',
    }),
    ...blades,
    item(`${id}-hub`, polygon(centerX, centerY, 12, 12, 10), '#737873', {
      ...shared,
      stroke: '#242724',
      lineWidth: 4,
      order: -59,
      surfaceNormal: { x: -0.35, y: -0.94 },
      role: 'ventilator-hub',
    }),
    item(`${id}-hub-bolt`, polygon(centerX, centerY, 4, 4, 8), '#9fa49d', {
      ...shared,
      stroke: '#30332f',
      lineWidth: 2,
      order: -58,
      surfaceNormal: { x: -0.2, y: -0.98 },
      role: 'ventilator-fastener',
    }),
  ];
}

