export function actorFor(resource) {
  if (resource.producer === 'player') return CAST_BRIEFS[0];
  if (resource.category !== 'npc') return null;
  return (
    CAST_BRIEFS.find(
      (a) =>
        a.match &&
        (typeof a.match === 'string' ? resource.id.includes(a.match) : a.match.test(resource.id)),
    ) ?? null
  );
}
